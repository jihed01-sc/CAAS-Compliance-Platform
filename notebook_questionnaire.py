def train_ia_model(initial_df: pd.DataFrame, followup_df: pd.DataFrame) -> Tuple[DecisionTreeClassifier, LabelEncoder, LabelEncoder, LabelEncoder, LabelEncoder]:
    """Train a decision tree model for risk analysis."""
    data = []
    if not initial_df.empty:
        for _, row in initial_df.iterrows():
            followup_status = (
                followup_df[followup_df["Question_ID"] == row["Question_ID"]]["Followup_Status"].iloc[0]
                if not followup_df.empty and "Question_ID" in followup_df.columns and row["Question_ID"] in followup_df["Question_ID"].values
                else "N/A"
            )
            data.append({
                "Domain": row["Domain"],
                "Compliance_Status": row["Compliance_Status"],
                "Followup_Status": followup_status,
                "Risk_Level": "High" if row["Compliance_Status"] == "Non-Compliant" else "Medium" if row["Compliance_Status"] == "Partially Compliant" else "Low"
            })
    df = pd.DataFrame(data) if data else pd.DataFrame()

    le_domain = LabelEncoder()
    le_status = LabelEncoder()
    le_followup = LabelEncoder()
    le_risk = LabelEncoder()

    if not df.empty:
        df["Domain"] = le_domain.fit_transform(df["Domain"])
        df["Compliance_Status"] = le_status.fit_transform(df["Compliance_Status"])
        df["Followup_Status"] = le_followup.fit_transform(df["Followup_Status"])
        df["Risk_Level"] = le_risk.fit_transform(df["Risk_Level"])
        X = df[["Domain", "Compliance_Status", "Followup_Status"]]
        y = df["Risk_Level"]
        model = DecisionTreeClassifier(random_state=42)
        model.fit(X, y)
    else:
        model = DecisionTreeClassifier(random_state=42)
        logger.warning("No data to train IA model; using default model")

    return model, le_domain, le_status, le_followup, le_risk

def predict_risk(model: DecisionTreeClassifier, le_domain: LabelEncoder, le_status: LabelEncoder,
                 le_followup: LabelEncoder, le_risk: LabelEncoder, row: Dict[str, Any]) -> str:
    """Predict risk level for a given row."""
    compliance_status = row.get("Compliance_Status", "Partially Compliant")
    followup_status = row.get("Followup_Status", "N/A")
    try:
        X = [[
            le_domain.transform([row["Domain"]])[0],
            le_status.transform([compliance_status])[0],
            le_followup.transform([followup_status])[0]
        ]]
        risk_idx = model.predict(X)[0]
        return le_risk.inverse_transform([risk_idx])[0]
    except Exception as e:
        logger.error(f"Error predicting risk for {row.get('Question_ID', 'unknown')}: {str(e)}")
        return "Medium"

def calculate_enhanced_metrics(responses_df: pd.DataFrame) -> Dict[str, Any]:
    """Calculate enhanced assessment metrics."""
    if responses_df.empty:
        logger.warning("Responses DataFrame is empty. Returning default metrics.")
        return {
            "error": "No responses available",
            "total_questions": 0,
            "applicable_questions": 0,
            "not_applicable_questions": 0,
            "compliance_percentage": 0.0,
            "weighted_compliance_percentage": 0.0,
            "maturity_level": "N/A",
            "domain_metrics": pd.DataFrame(),
            "high_risk_items_count": 0,
            "critical_gaps_count": 0,
            "standards_coverage": {},
            "fully_compliant": 0,
            "partially_compliant": 0,
            "non_compliant": 0
        }

    applicable_responses = responses_df[responses_df['Score'] >= 0]
    if applicable_responses.empty:
        logger.warning("No applicable responses found in responses_df.")
        return {
            "error": "No applicable responses found",
            "total_questions": len(responses_df),
            "applicable_questions": 0,
            "not_applicable_questions": len(responses_df),
            "compliance_percentage": 0.0,
            "weighted_compliance_percentage": 0.0,
            "maturity_level": "N/A",
            "domain_metrics": pd.DataFrame(),
            "high_risk_items_count": 0,
            "critical_gaps_count": 0,
            "standards_coverage": {},
            "fully_compliant": 0,
            "partially_compliant": 0,
            "non_compliant": 0
        }

    total_applicable = len(applicable_responses)
    total_score = applicable_responses['Score'].sum()
    max_possible_score = total_applicable * 2
    weighted_score = applicable_responses['Weighted_Score'].sum()
    max_weighted_score = applicable_responses['Risk_Weight'].sum() * 2

    compliance_percentage = (total_score / max_possible_score * 100) if max_possible_score > 0 else 0
    weighted_compliance_percentage = (weighted_score / max_weighted_score * 100) if max_weighted_score > 0 else 0
    maturity_level = get_enhanced_maturity_level(weighted_compliance_percentage)

    domain_metrics = applicable_responses.groupby('Domain').agg({
        'Score': ['sum', 'count'],
        'Weighted_Score': 'sum',
        'Risk_Weight': 'sum'
    }).round(2)
    domain_metrics.columns = ['Score_Sum', 'Question_Count', 'Weighted_Score_Sum', 'Risk_Weight_Sum']
    domain_metrics['Max_Score'] = domain_metrics['Question_Count'] * 2
    domain_metrics['Max_Weighted_Score'] = domain_metrics['Risk_Weight_Sum'] * 2
    domain_metrics['Compliance_Percentage'] = (domain_metrics['Score_Sum'] / domain_metrics['Max_Score'] * 100).round(2)
    domain_metrics['Weighted_Compliance_Percentage'] = (domain_metrics['Weighted_Score_Sum'] / domain_metrics['Max_Weighted_Score'] * 100).round(2)
    domain_metrics['Maturity_Level'] = domain_metrics['Weighted_Compliance_Percentage'].apply(get_enhanced_maturity_level)

    high_risk_items = applicable_responses[applicable_responses['Risk_Weight'] > 0.8]
    critical_gaps = applicable_responses[(applicable_responses['Risk_Weight'] > 0.8) & (applicable_responses['Score'] < 2)]

    standards_coverage = {}
    for _, row in applicable_responses.iterrows():
        standards = row['Applicable_Standards'].split(', ')
        for standard in standards:
            if standard not in standards_coverage:
                standards_coverage[standard] = {'total': 0, 'compliant': 0}
            standards_coverage[standard]['total'] += 1
            if row['Score'] == 2:
                standards_coverage[standard]['compliant'] += 1

    for standard in standards_coverage:
        total = standards_coverage[standard]['total']
        compliant = standards_coverage[standard]['compliant']
        standards_coverage[standard]['percentage'] = (compliant / total * 100) if total > 0 else 0

    return {
        'total_questions': len(responses_df),
        'applicable_questions': total_applicable,
        'not_applicable_questions': len(responses_df) - total_applicable,
        'total_score': total_score,
        'max_possible_score': max_possible_score,
        'weighted_score': weighted_score,
        'max_weighted_score': max_weighted_score,
        'compliance_percentage': compliance_percentage,
        'weighted_compliance_percentage': weighted_compliance_percentage,
        'maturity_level': maturity_level,
        'domain_metrics': domain_metrics,
        'high_risk_items_count': len(high_risk_items),
        'critical_gaps_count': len(critical_gaps),
        'standards_coverage': standards_coverage,
        'fully_compliant': len(applicable_responses[applicable_responses['Score'] == 2]),
        'partially_compliant': len(applicable_responses[applicable_responses['Score'] == 1]),
        'non_compliant': len(applicable_responses[applicable_responses['Score'] == 0])
    }

def get_enhanced_maturity_level(percentage: float) -> str:
    """Get enhanced maturity level based on percentage."""
    if percentage >= 91:
        return MaturityLevels.OPTIMIZED.value
    elif percentage >= 76:
        return MaturityLevels.MANAGED.value
    elif percentage >= 51:
        return MaturityLevels.DEFINED.value
    elif percentage >= 26:
        return MaturityLevels.DEVELOPING.value
    return MaturityLevels.INITIAL.value

