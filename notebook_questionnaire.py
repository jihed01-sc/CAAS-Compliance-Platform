    styles.add(ParagraphStyle(name='TableHeader', fontSize=12, leading=15, fontName=CONFIG["FONTS"]["TABLE_HEADER"], textColor=CONFIG["COLORS"]["HEADER_TEXT"], alignment=TA_CENTER))
    styles.add(ParagraphStyle(name='TableCell', fontSize=10, leading=12, fontName=CONFIG["FONTS"]["TABLE_CELL"]))

    elements = []

    # Validate input DataFrames
    required_response_columns = ['Question_ID', 'Domain', 'Question', 'Answer', 'Compliance_Status', 'Recommendation', 'Score']
    required_followup_columns = ['Question_ID', 'Domain', 'Previous_Recommendation', 'Followup_Status', 'New_Recommendation']
    domain_metrics_columns = ['Compliance_Percentage', 'Maturity_Level']

    if not responses_df.empty and not all(col in responses_df.columns for col in required_response_columns):
        missing_cols = set(required_response_columns) - set(responses_df.columns)
        logger.error(f"Missing required columns in responses_df: {missing_cols}")
        st.error(f"Invalid responses_df: Missing columns {missing_cols}")
        raise ValueError(f"Missing required columns in responses_df: {missing_cols}")

    if not followup_df.empty and not all(col in followup_df.columns for col in required_followup_columns):
        missing_cols = set(required_followup_columns) - set(followup_df.columns)
        logger.error(f"Missing required columns in followup_df: {missing_cols}")
        st.error(f"Invalid followup_df: Missing columns {missing_cols}")
        raise ValueError(f"Missing required columns in followup_df: {missing_cols}")

    # Ensure 'Domain' is a column in domain_metrics
    domain_metrics = metrics.get('domain_metrics', pd.DataFrame())
    if not domain_metrics.empty and 'Domain' not in domain_metrics.columns and domain_metrics.index.name == 'Domain':
        domain_metrics = domain_metrics.reset_index()
        metrics['domain_metrics'] = domain_metrics
        logger.info("Reset index to make 'Domain' a column in domain_metrics")

    if not domain_metrics.empty and not all(col in domain_metrics.columns for col in domain_metrics_columns):
        missing_cols = set(domain_metrics_columns) - set(domain_metrics.columns)
        logger.error(f"Missing required columns in domain_metrics: {missing_cols}")
        st.error(f"Invalid domain_metrics: Missing columns {missing_cols}")
        raise ValueError(f"Missing required columns in domain_metrics: {missing_cols}")

