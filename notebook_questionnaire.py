def harmonize_datasets(dataset1: Optional[pd.DataFrame], dataset2: Optional[pd.DataFrame]) -> pd.DataFrame:
    """Harmonize both datasets into a unified structure."""
    logger.info("Harmonizing datasets")
    unified_data = []
    used_control_ids = set()

    def generate_unique_control_id(base_id: str, idx: int, dataset_prefix: str) -> str:
        original_id = base_id
        suffix = 0
        while base_id in used_control_ids:
            suffix += 1
            base_id = f"{original_id}_{suffix}"
        used_control_ids.add(base_id)
        return base_id if original_id != base_id else f"{dataset_prefix}_{idx:04d}"

    for dataset, name, prefix in [(dataset1, "Dataset 1", "DS1"), (dataset2, "Dataset 2", "DS2")]:
        if dataset is not None and not dataset.empty:
            logger.info(f"Processing {name} with {len(dataset)} records")
            mappings = detect_column_mappings(dataset, name)
            for idx, row in dataset.iterrows():
                try:
                    domain_col = mappings.get('domain')
                    domain_value = str(row.get(domain_col, '')) if domain_col else ''
                    domain = map_domain_from_axe(domain_value)
                    if domain == "Unknown":
                        logger.warning(f"Skipping row {idx} in {name} due to unmapped domain: '{domain_value}'")
                        continue

                    desc_col = mappings.get('description')
                    control_desc = str(row.get(desc_col, f'Control from row {idx}')) if desc_col else f'Control from row {idx}'

                    control_id_col = mappings.get('control_id')
                    control_id = str(row.get(control_id_col, f'{prefix}_{idx:04d}')) if control_id_col else f'{prefix}_{idx:04d}'
                    control_id = generate_unique_control_id(control_id, idx, prefix)

                    standards_mapping = {}
                    for std_key, col_name in mappings.items():
                        if std_key.startswith('iso') or std_key.startswith('iec') or std_key.startswith('nis'):
                            if pd.notna(row.get(col_name)) and str(row.get(col_name)).strip():
                                if 'iso27001' in std_key and '2022' in std_key:
                                    standards_mapping['ISO27001:2022'] = str(row.get(col_name))
                                elif 'iso27001' in std_key and '2013' in std_key:
                                    standards_mapping['ISO27001:2013'] = str(row.get(col_name))
                                elif 'iec' in std_key:
                                    standards_mapping['IEC62443'] = str(row.get(col_name))
                                elif 'nis' in std_key:
                                    standards_mapping['NIS2'] = str(row.get(col_name))

                    unified_data.append({
                        'Control_ID': control_id,
                        'Domain': domain,
                        'Control_Description': control_desc,
                        'Standards_Mapping': standards_mapping,
                        'Applicable_Standards': list(standards_mapping.keys()),
                        'Source_Dataset': name,
                        'Risk_Weight': calculate_risk_weight(domain, standards_mapping),
                        'Complexity_Level': determine_complexity_level(control_desc)
                    })
                except Exception as e:
                    logger.warning(f"Error processing {name} row {idx}: {str(e)}")
                    continue

    if not unified_data:
        logger.error("No data processed")
        st.warning("No data loaded. Using sample data.")
        unified_data = create_sample_data()

    unified_df = pd.DataFrame(unified_data)
    logger.info(f"Harmonized {len(unified_df)} controls")
    logger.info(f"Domain distribution in unified_df: {unified_df['Domain'].value_counts().to_dict()}")
    return unified_df

