def calculate_risk_weight(domain: str, standards_mapping: Dict[str, str]) -> float:
    """Calculate risk weight based on domain and standards coverage."""
    base_weights = {
        Domains.GOVERNANCE_RISK.value: 0.9,
        Domains.ACCESS_IDENTITY.value: 0.95,
        Domains.ASSET_MANAGEMENT.value: 0.8,
        Domains.SECURITY_OPERATIONS.value: 0.85,
        Domains.INCIDENT_RESPONSE.value: 0.9,
        Domains.PHYSICAL_ENVIRONMENTAL.value: 0.7,
        Domains.NETWORK_COMMUNICATIONS.value: 0.85,
        Domains.SYSTEM_APPLICATION.value: 0.8,
        Domains.BUSINESS_CONTINUITY.value: 0.9,
        Domains.SUPPLIER_THIRD_PARTY.value: 0.75,
        Domains.HUMAN_RESOURCES.value: 0.7,
        Domains.CRYPTOGRAPHY.value: 0.85
    }
    base_weight = base_weights.get(domain, 0.8)
    standards_multiplier = 1.0 + (len(standards_mapping) * 0.1)
    return min(1.0, base_weight * standards_multiplier)

def determine_complexity_level(control_description: str) -> str:
    """Determine complexity level based on control description."""
    desc_lower = control_description.lower()
    high_complexity_keywords = ['implement', 'establish', 'develop', 'maintain', 'monitor', 'assess']
    medium_complexity_keywords = ['define', 'document', 'review', 'update', 'verify']
    high_count = sum(1 for keyword in high_complexity_keywords if keyword in desc_lower)
    medium_count = sum(1 for keyword in medium_complexity_keywords if keyword in desc_lower)
    if high_count >= 2:
        return "High"
    elif medium_count >= 2 or high_count >= 1:
        return "Medium"
    return "Low"

# Questionnaire Generation
def generate_enhanced_questionnaire(
    unified_df: pd.DataFrame,
    selected_standards: List[str],
    selected_domains: List[str],
    questions_per_domain: Dict[str, int],
    prioritize_high_risk: bool = True
) -> List[QuestionnaireItem]:
    """Generate an enhanced questionnaire with user-specified questions per domain."""
    logger.info(f"Generating questionnaire with questions per domain: {questions_per_domain}")
    if unified_df.empty:
        logger.warning("No unified data available, using sample data")
        unified_df = pd.DataFrame(create_sample_data())

    # Filter controls by selected standards and domains
    filtered_df = unified_df[
        (unified_df['Domain'].isin(selected_domains)) &
        (unified_df['Applicable_Standards'].apply(lambda x: any(std in x for std in selected_standards)))
    ].copy()

    if filtered_df.empty:
        logger.warning("No data matches the selected criteria, using sample data")
        filtered_df = pd.DataFrame(create_sample_data())
        filtered_df = filtered_df[
            (filtered_df['Domain'].isin(selected_domains)) &
            (filtered_df['Applicable_Standards'].apply(lambda x: any(std in x for std in selected_standards)))
        ]

    if filtered_df.empty:
        st.error(TRANSLATIONS[st.session_state.get('lang_code', 'en')]["error_no_questions"])
        logger.error("No controls available even after using sample data")
        return []

    # Log domain distribution
    domain_counts = filtered_df['Domain'].value_counts()
    logger.info(f"Controls per domain after filtering: {domain_counts.to_dict()}")

    questionnaire_items = []
    used_control_ids = set()

    for domain in selected_domains:
        num_questions = questions_per_domain.get(domain, 10)  # Default to 10 if not specified
        logger.info(f"Generating {num_questions} questions for domain: {domain}")
        domain_controls = filtered_df[filtered_df['Domain'] == domain].copy()

        if prioritize_high_risk:
            domain_controls = domain_controls.sort_values('Risk_Weight', ascending=False)

        # Select unique controls
        selected_controls = domain_controls[~domain_controls['Control_ID'].isin(used_control_ids)]

        if len(selected_controls) < num_questions:
            logger.warning(f"Insufficient controls for {domain}: {len(selected_controls)} available, {num_questions} requested")
            # Generate synthetic controls if needed
            additional_controls = generate_synthetic_controls(
                domain=domain,
                standards=selected_standards,
                num_needed=num_questions - len(selected_controls),
                existing_ids=used_control_ids
            )
            selected_controls = pd.concat([selected_controls, pd.DataFrame(additional_controls)], ignore_index=True)

        # Take exactly the number of questions requested
        selected_controls = selected_controls.head(num_questions)

        for _, control in selected_controls.iterrows():
            question_item = create_question_from_control(control)
            questionnaire_items.append(question_item)
            used_control_ids.add(control['Control_ID'])

        logger.info(f"Generated {len(selected_controls)} questions for {domain}")

    # Validate coverage
    domains_covered = set(item.domain for item in questionnaire_items)
    if len(domains_covered) < len(selected_domains):
        missing_domains = set(selected_domains) - domains_covered
        st.warning(f"No questions generated for domains: {', '.join(missing_domains)}. Check your data or selected standards.")
        logger.warning(f"No questions generated for domains: {missing_domains}")

    logger.info(f"Generated total of {len(questionnaire_items)} questions")
    return questionnaire_items

def generate_synthetic_controls(domain: str, standards: List[str], num_needed: int, existing_ids: set) -> List[Dict]:
    """Generate synthetic controls for domains with insufficient data."""
    synthetic_controls = []
    base_id = f"SYNTH_{domain.replace(' ', '_')}"
    for i in range(num_needed):
        control_id = f"{base_id}_{i:04d}"
        while control_id in existing_ids:
            i += 1
            control_id = f"{base_id}_{i:04d}"
        desc = f"Implement {domain.lower()} control {i+1}"
        standards_mapping = {std: f"Ref{i+1}" for std in standards}
        synthetic_controls.append({
            'Control_ID': control_id,
            'Domain': domain,
            'Control_Description': desc,
            'Standards_Mapping': standards_mapping,
            'Applicable_Standards': standards,
            'Source_Dataset': 'Synthetic',
            'Risk_Weight': calculate_risk_weight(domain, standards_mapping),
            'Complexity_Level': determine_complexity_level(desc)
        })
        existing_ids.add(control_id)
    logger.info(f"Generated {num_needed} synthetic controls for {domain}")
    return synthetic_controls

def create_question_from_control(control_row: pd.Series) -> QuestionnaireItem:
    """Create a questionnaire item from a control row."""
    control_mapping = ControlMapping(
        control_id=control_row['Control_ID'],
        description=control_row['Control_Description'],
        domain=control_row['Domain'],
        standards_mapping=control_row['Standards_Mapping'],
        implementation_guidance=generate_implementation_guidance(control_row)
    )
    question_text = generate_question_text(control_row['Control_Description'])
    return QuestionnaireItem(
        question_id=control_row['Control_ID'],
        domain=control_row['Domain'],
        question_text=question_text,
        applicable_standards=control_row['Applicable_Standards'],
        control_mapping=control_mapping,
        risk_weight=control_row['Risk_Weight'],
        complexity_level=control_row['Complexity_Level']
    )

def generate_question_text(control_description: str) -> str:
    """Generate an appropriate question from the control description."""
    desc = control_description.strip().lower()
    question_patterns = {
        'implement': 'Has your organization implemented {}?',
        'mettre en œuvre': 'Votre organisation a-t-elle mis en œuvre {}?',
        'establish': 'Has your organization established {}?',
        'établir': 'Votre organisation a-t-elle établi {}?',
        'maintain': 'Does your organization maintain {}?',
        'maintenir': 'Votre organisation maintient-elle {}?',
        'develop': 'Has your organization developed {}?',
        'développer': 'Votre organisation a-t-elle développé {}?',
        'define': 'Has your organization defined {}?',
        'définir': 'Votre organisation a-t-elle défini {}?',
        'document': 'Has your organization documented {}?',
        'documenter': 'Votre organisation a-t-elle documenté {}?',
        'review': 'Does your organization regularly review {}?',
        'réviser': 'Votre organisation révise-t-elle régulièrement {}?',
        'monitor': 'Does your organization monitor {}?',
        'surveiller': 'Votre organisation surveille-t-elle {}?',
        'assess': 'Does your organization assess {}?',
        'évaluer': 'Votre organisation évalue-t-elle {}?'
    }
    for verb, pattern in question_patterns.items():
        if verb in desc:
            cleaned_desc = desc.replace(verb, '').strip()
            if cleaned_desc.startswith('a ') or cleaned_desc.startswith('an '):
                cleaned_desc = cleaned_desc[2:].strip() if cleaned_desc.startswith('a ') else cleaned_desc[3:].strip()
            return pattern.format(cleaned_desc)
    return f"Does your organization have adequate controls for: {control_description}?"

def generate_implementation_guidance(control_row: pd.Series) -> str:
    """Generate implementation guidance based on control information."""
    domain = control_row['Domain']
    standards = control_row['Applicable_Standards']
    complexity = control_row['Complexity_Level']
    guidance_base = {
        Domains.GOVERNANCE_RISK.value: "Establish governance structures and risk management processes",
        Domains.ACCESS_IDENTITY.value: "Implement identity and access management controls",
        Domains.ASSET_MANAGEMENT.value: "Maintain comprehensive asset inventory and protection measures",
        Domains.SECURITY_OPERATIONS.value: "Deploy security monitoring and operational procedures",
        Domains.INCIDENT_RESPONSE.value: "Develop incident response and recovery capabilities",
        Domains.PHYSICAL_ENVIRONMENTAL.value: "Implement physical and environmental security controls",
        Domains.NETWORK_COMMUNICATIONS.value: "Secure network infrastructure and communications",
        Domains.SYSTEM_APPLICATION.value: "Apply security controls to systems and applications",
        Domains.BUSINESS_CONTINUITY.value: "Ensure business continuity and resilience planning",
        Domains.SUPPLIER_THIRD_PARTY.value: "Manage third-party and supplier security risks",
        Domains.HUMAN_RESOURCES.value: "Implement personnel security measures",
        Domains.CRYPTOGRAPHY.value: "Deploy appropriate cryptographic controls"
    }
    base_guidance = guidance_base.get(domain, "Implement appropriate security controls")
    guidance_suffix = {
        "High": " with comprehensive documentation, regular testing, and continuous improvement processes.",
        "Medium": " with proper documentation and periodic review.",
        "Low": " with basic documentation and annual review."
    }
    standards_note = f" Ensure compliance with: {', '.join(standards)}."
    return base_guidance + guidance_suffix.get(complexity, "") + standards_note

# Questionnaire and Follow-up Functions
def render_enhanced_questionnaire(questionnaire_items: List[QuestionnaireItem], lang: str = "en") -> pd.DataFrame:
    """Render the enhanced questionnaire with improved UX."""
    st.header(TRANSLATIONS[lang]["questionnaire"])
    st.info(TRANSLATIONS[lang]["questionnaire_info"])

    if 'responses' not in st.session_state:
        st.session_state.responses = []

    # Check for missing domains
    domains_covered = set(item.domain for item in questionnaire_items)
    selected_domains = set(st.session_state.get('selected_domains', []))
    if selected_domains and len(domains_covered) < len(selected_domains):
        missing_domains = selected_domains - domains_covered
        st.warning(f"No questions generated for domains: {', '.join(missing_domains)}. Check your data or selected standards.")
        logger.warning(f"No questions generated for domains: {missing_domains}")

    logger.info(f"Generated questions by domain: {dict(Counter(item.domain for item in questionnaire_items))}")

    progress_bar = st.progress(0)
    status_text = st.empty()

    questions_by_domain = {}
    for item in questionnaire_items:
        if item.domain not in questions_by_domain:
            questions_by_domain[item.domain] = []
        questions_by_domain[item.domain].append(item)

    question_counter = 0
    total_questions = len(questionnaire_items)

    for domain, domain_questions in questions_by_domain.items():
        st.subheader(f"🎯 {domain}")
        for item in domain_questions:
            question_counter += 1
            progress = question_counter / total_questions
            progress_bar.progress(progress)
            status_text.text(f"Question {question_counter} of {total_questions}")

            with st.container():
                st.markdown(f"**Question {question_counter}: {item.question_id}**")
                col1, col2 = st.columns([3, 1])
                with col1:
                    st.write(f"📋 {item.question_text}")
                    st.markdown(f"**Standards:** {' '.join([f'`{std}`' for std in item.applicable_standards])}")
                    risk_color = "🔴" if item.risk_weight > 0.8 else "🟡" if item.risk_weight > 0.6 else "🟢"
