def detect_column_mappings(df: pd.DataFrame, dataset_name: str) -> Dict[str, str]:
    """Detect column mappings automatically based on column content and names."""
    if df is None or df.empty:
        return {}

    mappings = {}
    columns = [col.lower().strip() for col in df.columns]
    original_columns = list(df.columns)

    logger.info(f"Detecting column mappings for {dataset_name}")
    patterns = {
        'domain': ['axe', 'domain', 'domaine', 'secteur'],
        'description': ['implement', 'description', 'contrôle', 'control', 'mesure', 'unified'],
        'control_id': ['id', 'identifiant', 'control_id', 'contol_id'],
        'iso27001_2022': ['iso 27001:2022', 'iso27001:2022', 'iso_27001_2022', 'iso 2022'],
        'iso27001_2013': ['iso27001:13', 'iso27001:2013', 'iso_27001_2013', 'iso 2013'],
        'iec62443': ['iec 62443', 'iec62443', 'iec_62443'],
        'nis2': ['nis2.0', 'nis2', 'nis_2', 'nis 2']
    }

    for target, keywords in patterns.items():
        best_match, best_score = None, 0
        for i, col in enumerate(columns):
            score = sum(100 if keyword == col else 50 if keyword in col else 0 for keyword in keywords)
            if score > best_score:
                best_score = score
                best_match = original_columns[i]
        if best_match and best_score > 0:
            mappings[target] = best_match
            logger.info(f"Mapped {target} -> {best_match} (score: {best_score})")

    return mappings

